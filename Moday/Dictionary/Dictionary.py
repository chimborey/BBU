# ================================= 4. Dictionary =================================

# ១. ការបង្កើត Dictionary
computer_info = {
    "brand": "ASUS",
    "ram_gb": 16,
    "is_ssd": True
}

# ២. ការទាញយកទិន្នន័យមកប្រើប្រាស់តាមរយៈ Key
print(computer_info["brand"])

# ៣. ការកែប្រែទិន្នន័យនៅក្នុង Dictionary
computer_info["ram_gb"] = 32

print(computer_info["ram_gb"], "GB")
